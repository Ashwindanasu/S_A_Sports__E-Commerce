function normalizeSearchText(value){

return value.toLowerCase().trim().split(/\s+/).map(word=>
word.length>3 && word.endsWith("s") ? word.slice(0,-1) : word
).join(" ");

}

function searchProduct(){

let text=normalizeSearchText(document.getElementById("searchInput").value);

if(text===""){

goHome();

return;
}

scrollToTop();

document.getElementById("homePage").classList.add("hidden");

document.getElementById("productPage").classList.add("hidden");

document.getElementById("detailPage").classList.add("hidden");

document.getElementById("searchPage").classList.remove("hidden");

let result=products.filter(p=>

normalizeSearchText(p.name).includes(text) ||

normalizeSearchText(p.category).includes(text) ||

normalizeSearchText(p.description).includes(text)

);

displayProducts(result,"searchResults");

}
